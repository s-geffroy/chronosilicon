export type Lang = 'fr' | 'en';
export const LANGS: readonly Lang[] = ['fr', 'en'];
export const MESSAGES: Readonly<Record<Lang, Readonly<Record<MessageKey, string>>>> = { fr, en };

export class MissingMessageError extends Error {
  override name = 'MissingMessageError';
}

export function translate(lang: Lang, key: string, params: Readonly<Record<string, string | number>> = {}): string {
  const table = MESSAGES[lang];
  if (!Object.hasOwn(table, key)) throw new MissingMessageError(`missing message "${key}" for ${lang}`);
  const raw = table[key as MessageKey];
  return raw.replace(/\{(\w+)\}/g, (_, name: string) => {
    if (!Object.hasOwn(params, name)) throw new MissingMessageError(`missing parameter "${name}" in "${key}"`);
    return String(params[name]);
  });
}
